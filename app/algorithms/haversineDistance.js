/**
 * Haversine 球面距离算法 —— 签到范围判定的数学内核
 * ============================================================================
 * 来源: assets/www/js/chunk-common.js  →  webpack module "46f3"
 *       组件 NeuGeoLocation 的 methods.getDistance
 * 还原档位: A（算法类，逐行等价 + 完整推导 + 用例）
 * 置信度: 高
 * ============================================================================
 *
 * 用途
 * ----------------------------------------------------------------------------
 * 学生签到 / 教师签到范围校验：把当前定位点与签到点做球面距离计算，
 * 与服务端下发的半径阈值比较，判断是否「在签到范围内」。
 * 调用方见 chunk-common/46f3（NeuGeoLocation 组件，getDistance 为其方法）。
 *
 * 算法
 * ----------------------------------------------------------------------------
 * Haversine（半正矢）公式，计算地球表面两点间的大圆距离：
 *
 *      a = sin²(Δφ/2) + cos φ₁ · cos φ₂ · sin²(Δλ/2)
 *      c = 2 · asin(√a)
 *      d = R · c
 *
 * 其中 φ 为纬度(rad)，λ 为经度(rad)，R 为地球半径。
 *
 * 原码用的是「2·asin(√a)」形式（等价于常用写法 2·atan2(√a, √(1−a))）；
 * asin 形式在 a 因浮点误差略大于 1 时会返回 NaN，这是本实现的已知边界风险。
 *
 * ★ 地球半径取 6378.137 km
 *   这是 WGS-84 椭球的**赤道半径**（a = 6378137 m），而非常用的
 *   平均半径 6371 km。两者在跨城计算时差异约 0.11%（约 1.1 km/1000km），
 *   在同一校园内（<5km）差异可忽略。
 *
 * ★ 结果保留 4 位小数（Math.round(v*1e4)/1e4），单位公里 → 精度 0.1 米。
 *
 * @param {number} lat1 起点纬度（十进制度，北纬为正）
 * @param {number} lng1 起点经度（十进制度，东经为正）
 * @param {number} lat2 终点纬度
 * @param {number} lng2 终点经度
 * @returns {number} 距离，单位**公里**，保留 4 位小数
 */
export function getDistance(lat1, lng1, lat2, lng2) {
  const EARTH_RADIUS_KM = 6378.137;

  const radLat1 = (lat1 * Math.PI) / 180; // φ₁
  const radLat2 = (lat2 * Math.PI) / 180; // φ₂
  const deltaLat = radLat1 - radLat2; // Δφ
  const deltaLng = (lng1 * Math.PI) / 180 - (lng2 * Math.PI) / 180; // Δλ

  const a =
    Math.pow(Math.sin(deltaLat / 2), 2) +
    Math.cos(radLat1) * Math.cos(radLat2) * Math.pow(Math.sin(deltaLng / 2), 2);

  const centralAngle = 2 * Math.asin(Math.sqrt(a)); // c
  const distanceKm = centralAngle * EARTH_RADIUS_KM;

  return Math.round(distanceKm * 1e4) / 1e4;
}

